# Generates `crates/cpp_formatter/src/presets.rs` from clang-format's own `-dump-config`.
#
# The formatter's style table has to be the oracle's own, or the two disagree in ways the audit then reports as rule
# bugs. This script is the only place that knowledge enters the repository: run it against the clang-format build
# named in `docs/cpp-format.md` §六 and the table follows.
#
#   pwsh tools/gen_presets.ps1
#   pwsh tools/gen_presets.ps1 -ClangFormat "C:\path\to\clang-format.exe"
#
# The dump is flattened to `key` / `value` pairs: nested maps become `Parent.Child`, sequences become `[a, b]`, and a
# sequence of maps (which nothing in the formatter reads) becomes `<n entries>`. A value that carries quotes or
# backslashes is emitted as a raw string, because a regex option does.

param(
    [string]$ClangFormat = "C:\Program Files\Microsoft Visual Studio\18\Community\VC\Tools\Llvm\x64\bin\clang-format.exe",
    [string]$Output = "crates/cpp_formatter/src/presets.rs"
)

$ErrorActionPreference = "Stop"
$presets = @("LLVM", "Google", "Chromium", "Mozilla", "WebKit", "Microsoft", "GNU")

$probe = Join-Path $env:TEMP "presets-probe.cpp"
"int x;" | Out-File -Encoding ascii $probe

function Format-Value([string]$value) {
    if ($value.Contains('"') -or $value.Contains('\') -or $value.Contains('#')) {
        # A raw string: `r#"…"#`. The dump never emits `"#`, so one hash is enough.
        return 'r#"' + $value + '"#'
    }
    return '"' + $value + '"'
}

function Format-Sequence($sequence) {
    $joined = $sequence -join ", "
    $isMap = $false
    foreach ($item in $sequence) {
        if ($item.Contains(":") -or $item.Contains("'")) { $isMap = $true; break }
    }
    if ($isMap -or $joined.Length -gt 80) {
        return '"<' + $sequence.Count + ' entries>"'
    }
    return Format-Value ("[" + $joined + "]")
}

function Get-Flattened($preset) {
    $raw = (& $ClangFormat "-style=$preset" -dump-config $probe 2>&1 | Out-String)
    $lines = @($raw -split "`r?`n")

    $pairs = [System.Collections.Generic.List[object]]::new()
    $parent = $null
    $sequence = $null
    $insideSequence = $false

    foreach ($line in $lines) {
        if ($line -match '^---') { continue }
        if ($line.Trim().Length -eq 0) { continue }
        $indent = $line.Length - $line.TrimStart().Length

        if ($indent -eq 0) {
            if ($null -ne $parent -and $null -ne $sequence) {
                $pairs.Add([pscustomobject]@{ Key = $parent; Literal = (Format-Sequence $sequence) })
            }
            $sequence = $null
            $insideSequence = $false
            $parent = $null

            if ($line -match '^([A-Za-z0-9_]+):\s*(.*)$') {
                $key = $matches[1]
                $value = $matches[2].Trim()
                if ($value.Length -eq 0) {
                    $parent = $key
                } elseif ($key -ne "Language") {
                    $pairs.Add([pscustomobject]@{ Key = $key; Literal = (Format-Value $value) })
                }
            }
            continue
        }

        if ($null -eq $parent) { continue }

        if ($line -match '^\s*-\s*(.*)$') {
            $insideSequence = $true
            if ($null -eq $sequence) {
                $sequence = [System.Collections.Generic.List[string]]::new()
            }
            $sequence.Add($matches[1].Trim().TrimEnd(':'))
            continue
        }

        if ($insideSequence) {
            # A field inside a sequence item (`IncludeCategories` is a list of maps).
            continue
        }

        if ($line -match '^\s+([A-Za-z0-9_]+):\s*(.*)$') {
            $pairs.Add([pscustomobject]@{
                Key     = "$parent.$($matches[1])"
                Literal = (Format-Value $matches[2].Trim())
            })
        }
    }

    if ($null -ne $parent -and $null -ne $sequence) {
        $pairs.Add([pscustomobject]@{ Key = $parent; Literal = (Format-Sequence $sequence) })
    }

    return $pairs
}

$llvm = Get-Flattened "LLVM"
$defaults = @{}
foreach ($pair in $llvm) { $defaults[$pair.Key] = $pair.Literal }

$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine("//! **The seven built-in presets**, flattened to ``key`` / ``value`` strings.")
[void]$out.AppendLine("//!")
[void]$out.AppendLine("//! Generated by ``tools/gen_presets.ps1`` from")
[void]$out.AppendLine("//! ``clang-format -style=<preset> -dump-config`` — **22.1.3**, the build in Visual Studio 18. Nested keys are")
[void]$out.AppendLine("//! ``Parent.Child``, sequences are ``[a, b]``. ``LLVM`` is the full table and every other preset is a delta")
[void]$out.AppendLine("//! against it, which is what ``BasedOnStyle`` means.")
[void]$out.AppendLine("")
[void]$out.AppendLine("/// The ``LLVM`` preset, which is also the base every other preset is a delta from.")
[void]$out.AppendLine("pub const LLVM: &[(&str, &str)] = &[")
foreach ($pair in $llvm) {
    [void]$out.AppendLine("    (""$($pair.Key)"", $($pair.Literal)),")
}
[void]$out.AppendLine("];")
[void]$out.AppendLine("")
[void]$out.AppendLine("/// **One preset's delta against ``LLVM``**: every key whose value it changes, and nothing else.")
[void]$out.AppendLine("pub fn delta(preset: &str) -> Option<&'static [(&'static str, &'static str)]> {")
[void]$out.AppendLine("    match preset {")
foreach ($preset in $presets[1..($presets.Count - 1)]) {
    $pairs = Get-Flattened $preset
    [void]$out.AppendLine("        ""$preset"" => Some(&[")
    foreach ($pair in $pairs) {
        $base = $null
        if ($defaults.ContainsKey($pair.Key)) { $base = $defaults[$pair.Key] }
        if ($base -ne $pair.Literal) {
            [void]$out.AppendLine("            (""$($pair.Key)"", $($pair.Literal)),")
        }
    }
    [void]$out.AppendLine("        ]),")
}
[void]$out.AppendLine("        _ => None,")
[void]$out.AppendLine("    }")
[void]$out.AppendLine("}")

# The list of keys clang-format accepts but does not dump is maintained by hand and survives a regeneration.
$previous = if (Test-Path $Output) { Get-Content $Output -Raw -Encoding utf8 } else { "" }
$deprecated = ""
$start = $previous.IndexOf("/// **Keys clang-format still accepts")
if ($start -ge 0) { $deprecated = "`r`n" + $previous.Substring($start) }

Set-Content -Path $Output -Value ([string]::Concat($out.ToString(), $deprecated)) -Encoding utf8 -NoNewline
"$($llvm.Count) keys from $ClangFormat"
