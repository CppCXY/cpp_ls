    /// The key as clang-format spells it, including the dotted form of a nested option.
    pub fn key(self) -> &'static str {
        KEYS[self as usize]
    }

    /// The option a key names, if any. Used by the loader, where a string search is the right cost.
    pub fn from_key(key: &str) -> Option<StyleOption> {
        StyleOption::ALL
            .binary_search_by(|option| option.key().cmp(key))
            .ok()
            .map(|at| StyleOption::ALL[at])
    }
