#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_is_reachable_by_name() {
        for option in StyleOption::ALL {
            assert_eq!(StyleOption::from_key(option.key()), Some(option));
        }
        assert_eq!(StyleOption::from_key("NoSuchKey"), None);
    }

    #[test]
    fn all_is_sorted_by_key_and_covers_every_index() {
        let keys: Vec<&str> = StyleOption::ALL.iter().map(|option| option.key()).collect();
        let mut sorted = keys.clone();
        sorted.sort_unstable();
        assert_eq!(keys, sorted, "the dump prints in the oracle's order, and rom_key relies on it");

        let mut indices: Vec<usize> = StyleOption::ALL.iter().map(|option| *option as usize).collect();
        let count = indices.len();
        indices.sort_unstable();
        indices.dedup();
        assert_eq!(indices.len(), count);
        assert_eq!(indices.first().copied(), Some(0));
        assert_eq!(indices.last().copied(), Some(StyleOption::COUNT - 1));
    }
}
