//! **Every style option, as a Rust enum whose discriminant is its index in [crate::config::Style].**
//!
//! Generated from `presets.rs` (which is generated from `clang-format -dump-config`), so the enum and the
//! oracle cannot drift: the key strings are the oracle's own and `StyleOption::COUNT` is the number it prints.
//!
//! A style query is `values[option as usize]` — one bounds-checked index, no string hashing and no parsing. The
//! string form is used exactly twice: reading a `.clang-format` and printing `-dump-config`.
//!
//! **`KEYS` is in declaration order and `ALL` is sorted by key, byte for byte.** The discriminant has to match
//! the array the style stores, so variants follow the preset table; the dump and `from_key` want the oracle's
//! alphabetical order, so `ALL` is that order and the lookup is a binary search over it.

/// One style option. `as usize` is its index in the resolved style's array.
